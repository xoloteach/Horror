def tex_runes():
    s = SIZE
    img = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    n = len(RUNES)
    cell = s // n
    pad = cell // 4
    for idx, strokes in enumerate(RUNES):
        ox = idx * cell + pad
        oy = s // 2 - (cell - 2 * pad) // 2
        cw, ch = cell - 2 * pad, cell - 2 * pad
        for (x0, y0), (x1, y1) in strokes:
            d.line([ox + x0 / 4.0 * cw, oy + y0 / 6.0 * ch,
                    ox + x1 / 4.0 * cw, oy + y1 / 6.0 * ch],
                   fill=(235, 240, 255, 255), width=max(3, cell // 16))
    # faint second row, offset, dimmer — usable as a longer strip
    for idx, strokes in enumerate(RUNES):
        ox = idx * cell + pad + cell // 2
        if ox + cell > s:
            break
        oy = s // 2 - (cell - 2 * pad) // 2
        cw, ch = cell - 2 * pad, cell - 2 * pad
        for (x0, y0), (x1, y1) in strokes:
            d.line([ox + x0 / 4.0 * cw, oy + y0 / 6.0 * ch,
                    ox + x1 / 4.0 * cw, oy + y1 / 6.0 * ch],
                   fill=(200, 210, 235, 140), width=max(2, cell // 20))
    img.save(os.path.join(TEX_DIR, "runes_alpha.png"))

def tex_frozeneath():
    s = SIZE
    soil = fbm(s, 5, 5)
    detail = fbm(s, 20, 3)
    ice_field = fbm(s, 3, 4)
    ice = np.clip((ice_field - 0.58) * 6.0, 0.0, 1.0)
    ice = np.clip(ice + 0.3 * np.clip((fbm(s, 8, 3) - 0.55) * 5.0, 0, 1), 0, 1)
    height = 0.6 * soil + 0.25 * detail + 0.15 * ice_field
    base_r = (0.23 + 0.10 * (soil - 0.5) * 2.0) * 255.0
    base_g = (0.19 + 0.09 * (soil - 0.5) * 2.0) * 255.0
    base_b = (0.16 + 0.08 * (soil - 0.5) * 2.0) * 255.0
    sparkle = (detail > 0.93).astype(float) * ice
    r = base_r * (1 - ice) + (185.0 + 40.0 * sparkle) * ice
    g = base_g * (1 - ice) + (210.0 + 30.0 * sparkle) * ice
    b = base_b * (1 - ice) + (235.0 + 20.0 * sparkle) * ice
    save_rgb(os.path.join(TEX_DIR, "frozeneath_albedo.png"), np.stack([r, g, b], axis=-1))
    save_rgb(os.path.join(TEX_DIR, "frozeneath_normal.png"),
             height_to_normal(height + 0.2 * ice, strength=1.8))

# --------------------------------------------------------------------- driver
def main():
    manifest = []
    print("== SFX ==")
    for name, target_dur, fn in SFX_JOBS:
        sig = fn()
        path = os.path.join(AUDIO_DIR, name)
        actual_dur = write_wav(path, sig)
        size = os.path.getsize(path)
        assert size > 0, f"empty file: {path}"
        peak = float(np.max(np.abs(fade(peak_normalize(sig)))))
        manifest.append(("audio/" + name, size, f"{actual_dur:.2f}s (target {target_dur:.2f}s)",
                         f"peak {20*np.log10(max(peak,1e-9)):.1f} dBFS"))
        print(f"  {name}: {size} bytes, {actual_dur:.2f}s")

    print("== TEXTURES ==")
    for name, fn in [("stone", tex_stone), ("iron", tex_iron),
                     ("runes", tex_runes), ("frozeneath", tex_frozeneath)]:
        fn()
    for f in sorted(os.listdir(TEX_DIR)):
        path = os.path.join(TEX_DIR, f)
        size = os.path.getsize(path)
        assert size > 0, f"empty file: {path}"
        with Image.open(path) as im:
            dims = f"{im.size[0]}x{im.size[1]} {im.mode}"
        manifest.append(("textures/" + f, size, dims, ""))
        print(f"  {f}: {size} bytes, {dims}")

    total = sum(m[1] for m in manifest)
    print(f"\nTotal files: {len(manifest)}, total size: {total/1024/1024:.2f} MB")
    assert total < 200 * 1024 * 1024, "output exceeds 200MB budget"

    # final verification pass
    expected_audio = [j[0] for j in SFX_JOBS]
    expected_tex = ["stone_albedo.png", "stone_normal.png", "stone_roughness.png",
                    "iron_albedo.png", "iron_roughness.png", "runes_alpha.png",
                    "frozeneath_albedo.png", "frozeneath_normal.png"]
    for f in expected_audio:
        p = os.path.join(AUDIO_DIR, f)
        assert os.path.isfile(p) and os.path.getsize(p) > 0, f"MISSING: {p}"
    for f in expected_tex:
        p = os.path.join(TEX_DIR, f)
        assert os.path.isfile(p) and os.path.getsize(p) > 0, f"MISSING: {p}"
    print("All deliverables verified: 12 WAVs + 8 PNGs present and non-empty.")
    return manifest

if __name__ == "__main__":
    main()
