# ------------------------------------------------------------- texture utils
def periodic_value_noise(size, cells):
    lat = rng.random((cells, cells))
    t = np.linspace(0.0, cells, size, endpoint=False)
    fl = np.floor(t)
    i0 = fl.astype(np.int64) % cells
    f = t - fl
    s = f * f * (3.0 - 2.0 * f)
    i1 = (i0 + 1) % cells
    top = lat[:, i0] * (1.0 - s)[None, :] + lat[:, i1] * s[None, :]
    A = top[i0, :]
    B = top[i1, :]
    w = s[:, None]
    return A * (1.0 - w) + B * w

def fbm(size, base_cells, octaves):
    total = np.zeros((size, size))
    amp, freq, norm = 1.0, base_cells, 0.0
    for _ in range(octaves):
        total += amp * periodic_value_noise(size, freq)
        norm += amp
        amp *= 0.5
        freq *= 2
    return total / norm

def height_to_normal(h, strength=2.0):
    dx = (np.roll(h, -1, axis=1) - np.roll(h, 1, axis=1)) * 0.5 * strength
    dy = (np.roll(h, -1, axis=0) - np.roll(h, 1, axis=0)) * 0.5 * strength
    n = np.stack([-dx, -dy, np.ones_like(h)], axis=-1)
    n /= np.linalg.norm(n, axis=-1, keepdims=True) + 1e-9
    return ((n * 0.5 + 0.5) * 255.0).astype(np.uint8)

def save_rgb(path, arr):
    Image.fromarray(np.clip(arr, 0, 255).astype(np.uint8), "RGB").save(path)

def save_gray(path, arr):
    Image.fromarray(np.clip(arr, 0, 255).astype(np.uint8), "L").save(path)

# ------------------------------------------------------------------ textures
def tex_stone():
    s = SIZE
    base = fbm(s, 4, 5)
    detail = fbm(s, 16, 4)
    height = 0.65 * base + 0.35 * detail
    crack_field = fbm(s, 6, 4)
    cracks = np.clip(1.0 - np.abs(crack_field - 0.5) * 9.0, 0.0, 1.0)
    fine = np.clip(1.0 - np.abs(fbm(s, 24, 3) - 0.5) * 14.0, 0.0, 1.0)
    crack_all = np.clip(cracks + 0.6 * fine, 0.0, 1.0)
    moss_mask = np.clip((fbm(s, 3, 3) - 0.55) * 4.0, 0.0, 1.0) * np.clip((0.45 - height) * 4.0, 0.0, 1.0)
    gray = 0.42 + 0.16 * (base - 0.5) * 2.0 + 0.06 * (detail - 0.5) * 2.0
    gray = np.clip(gray - 0.28 * crack_all, 0.05, 1.0)
    r = gray * 255.0
    g = gray * 252.0
    b = gray * 244.0
    r = r * (1 - 0.25 * moss_mask) + 90.0 * moss_mask
    g = g * (1 - 0.15 * moss_mask) + 115.0 * moss_mask
    b = b * (1 - 0.35 * moss_mask) + 70.0 * moss_mask
    save_rgb(os.path.join(TEX_DIR, "stone_albedo.png"), np.stack([r, g, b], axis=-1))
    save_rgb(os.path.join(TEX_DIR, "stone_normal.png"),
             height_to_normal(height - 0.55 * crack_all, strength=2.5))
    rough = 200.0 + 35.0 * crack_all + 25.0 * moss_mask - 20.0 * (detail - 0.5)
    save_gray(os.path.join(TEX_DIR, "stone_roughness.png"), rough)

def tex_iron():
    s = SIZE
    # brushed: stretched noise (few cells vertically -> horizontal streaks)
    lat = rng.random((4, 96))
    ty = np.linspace(0.0, 4, s, endpoint=False)
    tx = np.linspace(0.0, 96, s, endpoint=False)
    fy = ty - np.floor(ty); sy = fy * fy * (3 - 2 * fy)
    fx = tx - np.floor(tx); sx = fx * fx * (3 - 2 * fx)
    iy0 = np.floor(ty).astype(int) % 4; iy1 = (iy0 + 1) % 4
    ix0 = np.floor(tx).astype(int) % 96; ix1 = (ix0 + 1) % 96
    a = lat[iy0][:, ix0] * (1 - sx)[None, :] + lat[iy0][:, ix1] * sx[None, :]
    b = lat[iy1][:, ix0] * (1 - sx)[None, :] + lat[iy1][:, ix1] * sx[None, :]
    streak = a * (1 - sy)[:, None] + b * sy[:, None]
    var = fbm(s, 4, 4)
    wear = np.clip((fbm(s, 3, 3) - 0.60) * 5.0, 0.0, 1.0)
    base = 0.16 + 0.035 * (streak - 0.5) * 2.0 + 0.03 * (var - 0.5) * 2.0
    base = np.clip(base + 0.06 * wear, 0.02, 1.0)
    r = base * 255.0
    g = (base * 1.04) * 255.0
    bch = (base * 1.18) * 255.0
    save_rgb(os.path.join(TEX_DIR, "iron_albedo.png"), np.stack([r, g, bch], axis=-1))
    rough = 150.0 + 45.0 * (streak - 0.5) * 2.0 - 50.0 * wear + 20.0 * (var - 0.5) * 2.0
    save_gray(os.path.join(TEX_DIR, "iron_roughness.png"), rough)

